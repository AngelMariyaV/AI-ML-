import numpy as np
import pandas as pd
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.preprocessing.sequence import pad_sequences
from tensorflow.keras.utils import to_categorical

data="""my name is Anand maurya I have 16 Gb ram laptop"""

# tokenizer
tokenizer=Tokenizer()
tokenizer.fit_on_texts([data])
# total number of words
total_words=len(tokenizer.word_index)+1
print(tokenizer.word_index)
print(total_words)

# input seq
input_seq=[]
for line in data.split('.'):
    token_list=tokenizer.texts_to_sequences([line])[0]
    for i in range(1,len(token_list)):
        n_gram_seq=token_list[:i+1]
        input_seq.append(n_gram_seq)
print(input_seq)

# padding seq
max_len=max([len(x) for x in input_seq])
# pads all seq to the same len with xers at the begining
input_seq=np.array(pad_sequences
          (input_seq,
           maxlen=max_len,
           padding='pre'))
print(input_seq)

# Building the model
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding,LSTM,Dense,Dropout
from tensorflow.keras.optimizers import Adam

model=Sequential()
# model.add(Embedding(total number of unique words in your tokenizer,size of the vector, number of vector in each input))
model.add(Embedding(total_words,10,input_length=max_len-1))
model.add(LSTM(120,return_sequences=True))
model.add(Dropout(0.1))
model.add(LSTM(100))
model.add(Dense(total_words,activation='softmax'))
model.compile(loss='categorical_crossentropy',
              optimizer=Adam (learning_rate=0.1),
              metrics=["accuracy"])
model.summary()

x=input_seq[:,:-1]
y=input_seq[:,-1]
y=to_categorical(y,num_classes=total_words)

x.shape

y.shape

history=model.fit(x,y,epochs=100,verbose=1)

# predicting next word
def predict_next_word(model,tokenizer,text,max_len):
  token_list=tokenizer.texts_to_sequences([text])[0]
  token_list=pad_sequences([token_list],maxlen=max_len-1,padding='pre')
  prediction=model.predict(token_list)
  prediction_word_index=np.argmax(prediction)
  predicted_word=tokenizer.index_word[prediction_word_index]
  return predicted_word

print(predict_next_word(model,tokenizer,"anand",max_len))

text = "my"

while len(text) < max_len:
    next_word = predict_next_word(model, tokenizer, text, max_len)
    print(next_word)
    text += " " + next_word

print(text)

